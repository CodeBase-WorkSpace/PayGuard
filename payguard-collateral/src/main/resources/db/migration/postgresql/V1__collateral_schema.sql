CREATE TABLE collateral (
    id uuid PRIMARY KEY, owner_token varchar(128) NOT NULL, loan_id uuid NOT NULL,
    amount numeric(28,8) NOT NULL, asset_currency char(3) NOT NULL,
    warning_ltv numeric(10,8) NOT NULL, margin_ltv numeric(10,8) NOT NULL,
    liquidation_ltv numeric(10,8) NOT NULL, status varchar(24) NOT NULL,
    version bigint DEFAULT 0 NOT NULL, retention_until timestamptz(6),
    created_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX ix_collateral_loan_status ON collateral(loan_id, status);
CREATE TABLE collateral_valuation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collateral_id uuid NOT NULL REFERENCES collateral(id),
    asset_value numeric(28,8) NOT NULL, fx_rate numeric(28,12) NOT NULL,
    observed_at timestamptz(6) NOT NULL
);
CREATE INDEX ix_collateral_val_time ON collateral_valuation(collateral_id, observed_at);
CREATE TABLE collateral_audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collateral_id uuid NOT NULL, subject_token varchar(128), actor_token varchar(128),
    action varchar(64) NOT NULL, reason varchar(256),
    occurred_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    previous_hash varchar(128), record_hash varchar(128) NOT NULL
);
CREATE INDEX ix_collateral_audit_subject_time ON collateral_audit_log(subject_token, occurred_at);
CREATE TABLE collateral_processed_event (
    event_id uuid NOT NULL, consumer_name varchar(128) NOT NULL,
    processed_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY(event_id, consumer_name)
);
CREATE TABLE collateral_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid UNIQUE NOT NULL, event_type varchar(128) NOT NULL,
    aggregate_id varchar(128) NOT NULL, payload text NOT NULL,
    occurred_at timestamptz(6) NOT NULL, published_at timestamptz(6)
);
