CREATE TABLE loan_account (
    id uuid PRIMARY KEY,
    borrower_token varchar(128) NOT NULL,
    collateral_id uuid NOT NULL,
    principal numeric(28,8) NOT NULL,
    annual_rate numeric(20,12) NOT NULL,
    term_months integer NOT NULL,
    status varchar(24) NOT NULL,
    outstanding_principal numeric(28,8) NOT NULL,
    accrued_interest numeric(28,8) NOT NULL,
    last_accrual_date date NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    retention_until timestamptz(6),
    created_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX ix_loan_due ON loan_account(status, last_accrual_date);
CREATE TABLE loan_audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id uuid NOT NULL,
    subject_token varchar(128), actor_token varchar(128),
    action varchar(64) NOT NULL, reason varchar(256),
    occurred_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    previous_hash varchar(128), record_hash varchar(128) NOT NULL
);
CREATE INDEX ix_loan_audit_subject_time ON loan_audit_log(subject_token, occurred_at);
CREATE TABLE loan_processed_event (
    event_id uuid NOT NULL, consumer_name varchar(128) NOT NULL,
    processed_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY(event_id, consumer_name)
);
CREATE TABLE loan_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid UNIQUE NOT NULL, event_type varchar(128) NOT NULL,
    aggregate_id varchar(128) NOT NULL, payload text NOT NULL,
    occurred_at timestamptz(6) NOT NULL, published_at timestamptz(6)
);
